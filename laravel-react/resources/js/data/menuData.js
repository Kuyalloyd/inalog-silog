export const featuredMenuNames = ['Chicken Inasal', 'Crispy Pata', 'Laing', 'Pancit Canton', 'Garlic Butter Shrimp', 'Bulalo'];

export function getFeaturedMenuItems() {
    return featuredMenuNames
        .map((name) => menuItems.find((item) => item.name === name))
        .filter(Boolean);
}

export function getMenuItemsByCategory(category) {
    return menuItems.filter((item) => item.category === category);
}
